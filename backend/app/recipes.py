def resolve(dish):
    text = (dish or "").strip()
    if not text:
        return {"reply": "Уточните, пожалуйста, название блюда."}

    lemmas = lemma_set(text)
    for name, recipe in RECIPES.items():
        if name in lemmas or name in text.lower():
            return {"reply": recipe}

    return {
        "reply": (
            f"Точного рецепта для «{text}» у меня нет. Общий принцип: подготовьте продукты, "
            "начните с обжарки лука и специй, затем добавьте основу и тушите до готовности. "
            "Солите постепенно и пробуйте блюдо."
        )
    }
