def resolve(country):
    text = (country or "").strip()
    if not text:
        return {"reply": "Уточните, пожалуйста, название страны."}

    lemmas = lemma_set(text)
    for name, facts in COUNTRY_FACTS.items():
        if name in lemmas or name in text.lower():
            return {"reply": facts}

    return {
        "reply": (
            f"О стране «{text}» подробностей у меня нет, но подскажу общее: проверьте визовый режим, "
            "срок действия загранпаспорта (от 6 месяцев), оформите страховку и уточните сезон. "
            "Могу рассказать о Турции, Египте, ОАЭ, Италии, Франции, Грузии, Японии или Таиланде."
        )
    }
